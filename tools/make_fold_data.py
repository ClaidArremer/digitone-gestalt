"""Writes src/fold_data.h: the wavefolder's tables (GESTALT 5.0). usage: make_fold_data.py out.h"""
import math, sys
out = sys.argv[1]
L = []
w = L.append
w('/* GESTALT\'s wavefolder: its tables, generated by tools/make_fold_data.py (do not edit). */')
w('#ifndef FOLD_DATA_H\n#define FOLD_DATA_H')
# a 1024-entry sine, Q15 (the page's reference)
s = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
w('static const short fd_sin[1024] = {')
for i in range(0, 1024, 16): w('    ' + ', '.join('%d' % v for v in s[i:i + 16]) + ',')
w('};')
# SHAPE: seven fold curves over a turn (index 256 = a quarter turn = a full-scale input at drive 1),
# each scaled to the sine's power at 0.8 of full scale (so heavy folding comes out at one level
# whatever the shape), peaks held to full scale. SHAPE morphs between neighbours.
def tri(t):  # peak at a quarter turn
    u = (t / (2 * math.pi)) % 1.0
    return 4 * u if u < .25 else 2 - 4 * u if u < .75 else 4 * u - 4
def sqr(t): return math.tanh(3 * math.sin(t)) / math.tanh(3)
def step(t):  # a staircase sine, eight levels, no level at zero (small signals: a fuzz)
    v = math.sin(t); q = math.floor(v * 4) + 0.5
    return max(-3.5, min(3.5, q)) / 3.5
def ripl(t): return (math.sin(t) + 0.6 * math.sin(3 * t)) / 1.0
def wrap(t):  # a saw at two a turn: rises to full scale at a quarter turn, then drops: the wrap
    u = (t / math.pi + 0.5) % 1.0
    return 0.0 if abs(u) < 1e-9 else 2 * u - 1     # the jump itself at 0, so it stays odd (no DC)
def lean(t):  # lopsided: the top rounder, the bottom folded harder (even harmonics, DC)
    v = math.sin(t)
    return v + 0.55 * (v * v - 0.5) if v >= 0 else v - 0.55 * math.sin(2 * t) ** 2 + 0.55 * (v * v - 0.5)
shapes = [('SINE', math.sin), ('TRI', tri), ('SQR', sqr), ('STEP', step), ('RIPL', ripl), ('WRAP', wrap), ('LEAN', lean)]
tabs = []
for name, f in shapes:
    v = [f(2 * math.pi * i / 1024) for i in range(1024)]
    m = sum(v) / 1024
    pk = max(abs(x) for x in v)
    v = [x / pk for x in v]
    rms = math.sqrt(sum(x * x for x in v) / 1024)
    k = min(0.8 * (1 / math.sqrt(2)) / rms, 1.0)
    tabs.append([round(32767 * k * x) for x in v])
    print('shape %-4s rms %.3f gain %.3f mean %+.3f' % (name, rms, k, m))
w('/* SHAPE: the fold curves, Q15: ' + ', '.join(n for n, f in shapes) + ' */')
w('#define FD_SHAPES %d' % len(shapes))
w('static const short fd_shape[FD_SHAPES][1024] = {')
for t in tabs:
    w('  {')
    for i in range(0, 1024, 16): w('    ' + ', '.join('%d' % v for v in t[i:i + 16]) + ',')
    w('  },')
w('};')
pts = [round(127 * i / (len(shapes) - 1)) for i in range(len(shapes))]
w('/* SHAPE: where each curve sits on the knob, and its name */')
w('static const unsigned char fd_shape_pt[FD_SHAPES] = {' + ', '.join(map(str, pts)) + '};')
w('static const char *const fd_shape_name[FD_SHAPES] = {' + ', '.join('"%s"' % n for n, f in shapes) + '};')
# FOLD 1..127: the drive G = 2^(5 (f - 1) / 126), 1 .. 32, as Q11 (capped at 65535); 0: OFF (1.0)
gq = [2048] + [min(65535, round(2048 * 2 ** (5 * (f - 1) / 126))) for f in range(1, 128)]
w('/* FOLD: the drive into the sine, Q11 (2048 = a full-scale input reaches the sine\'s peak) */')
w('static const unsigned short fd_gq[128] = {' + ', '.join(map(str, gq)) + '};')
# the folded signal's trim, by FOLD (x1.25: the shapes sit at 0.8 of full scale): 2 / pi (the sine's slope at the centre: -3.9 dB), and the drive
# back off up to 8 dB of it; past that the folds hold their own level (about -1 to -3 dBFS RMS), so
# the trim stays at -11.9 dB. Q15; it scales the sine table the loop reads, so it costs nothing a sample
def trim(f):
    d = 30 * (f - 1) / 126
    return min(32767, round(1.25 * 32768 * 10 ** ((-20 * math.log10(math.pi / 2) - min(d, 8)) / 20)))
tr = [trim(1)] + [trim(f) for f in range(1, 128)]
w('/* FOLD: the trim on the folded signal, Q15 (-3.9 dB, less the drive up to 8 dB) */')
w('static const unsigned short fd_trim[128] = {' + ', '.join(map(str, tr)) + '};')
# TONE: a one-pole low-pass after the folder, 300 Hz (0) .. 16 kHz (126), open (127)
hz = [300 * (16000 / 300) ** (t / 126) for t in range(127)] + [24000]
k = [min(32767, round(32768 * (1 - math.exp(-2 * math.pi * f / 48000)))) for f in hz]
k[127] = 32768
w('/* TONE: the low-pass coefficient, Q15 (32768: open), and its corner in Hz / 10 for the page */')
w('static const unsigned short fd_tone_k[128] = {' + ', '.join(map(str, [min(x, 65535) for x in k])) + '};')
w('static const unsigned short fd_tone_hz10[128] = {' + ', '.join(str(round(f / 10)) for f in hz) + '};')
def near(target):
    return min(range(127), key=lambda t: abs(hz[t] - target))
snaps = sorted(set([near(f) for f in (500, 1000, 2000, 4000, 8000, 12000)] + [127]))
w('/* FUNC + TONE: 500 Hz, 1k, 2k, 4k, 8k, 12k, OPEN */')
w('static const unsigned char fd_snap_tone[] = {' + ', '.join(map(str, snaps)) + '};')
w('#endif')
open(out, 'w').write('\n'.join(L) + '\n')
print('written', out, 'tone snaps', snaps, [round(hz[t]) for t in snaps])
